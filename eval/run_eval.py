"""Run the agent on every question in eval/questions.json and write eval/results.md.

    python -m eval.run_eval                      # all questions, model from .env
    python -m eval.run_eval --only refund-half   # some questions (comma-separated ids)
    python -m eval.run_eval --model gemini-3.1-flash-lite --output eval/results-3.1-flash-lite.md

Each question gets a fresh conversation. A question with "turns" is a short
conversation; the checks then apply to the last answer and to all tool calls.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import time
from collections.abc import Callable
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path

from dotenv import load_dotenv

from helpdesk.agent import Agent, ToolCallRecord
from helpdesk.config import PROJECT_ROOT, ConfigError, LLMSettings
from helpdesk.factory import build_agent
from helpdesk.llm import LLMError

from .checks import Check, run_checks

QUESTIONS_FILE = PROJECT_ROOT / "eval" / "questions.json"
RESULTS_FILE = PROJECT_ROOT / "eval" / "results.md"


@dataclass
class CaseResult:
    case: dict
    answers: list[str] = field(default_factory=list)
    tool_calls: list[ToolCallRecord] = field(default_factory=list)
    checks: list[Check] = field(default_factory=list)
    error: str | None = None
    seconds: float = 0.0
    model_calls: int = 0
    retries: int = 0  # extra attempts after rate limits or server errors

    @property
    def passed(self) -> bool:
        return self.error is None and all(check.passed for check in self.checks)

    @property
    def status(self) -> str:
        return "ERROR" if self.error else ("PASS" if self.passed else "FAIL")


def load_cases(path: Path = QUESTIONS_FILE) -> list[dict]:
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def run_case(agent: Agent, case: dict) -> CaseResult:
    result = CaseResult(case)
    started = time.monotonic()
    try:
        for turn in case.get("turns") or [case["question"]]:
            reply = agent.ask(turn)
            result.answers.append(reply.answer)
            result.tool_calls.extend(reply.tool_calls)
            result.model_calls += reply.model_calls
    except LLMError as exc:
        result.error = str(exc)
    else:
        language = case.get("language", "en")
        result.checks = run_checks(case["checks"], result.answers[-1], result.tool_calls, language)
    result.seconds = time.monotonic() - started
    stats = getattr(agent.model, "stats", None)  # only the real model counts retries
    result.retries = stats.retries if stats else 0
    return result


def run_all(cases: list[dict], make_agent: Callable[[], Agent], delay: float = 0.0) -> list[CaseResult]:
    results = []
    for i, case in enumerate(cases, start=1):
        if i > 1 and delay:
            time.sleep(delay)  # stay under the free tier's requests-per-minute limit
        print(f"[{i}/{len(cases)}] {case['id']} ... ", end="", flush=True)
        result = run_case(make_agent(), case)
        print(result.status + (f" ({result.error})" if result.error else ""))
        results.append(result)
    return results


# --- report -------------------------------------------------------------------


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _quote(text: str) -> str:
    return "\n".join("> " + line if line.strip() else ">" for line in text.strip().splitlines())


def render_report(
    results: list[CaseResult], model: str, base_url: str, run_at: datetime, code_version: str = "unknown"
) -> str:
    passed = sum(r.passed for r in results)
    errors = sum(r.error is not None for r in results)
    failed = len(results) - passed - errors
    minutes = sum(r.seconds for r in results) / 60
    lines = [
        "# Evaluation results",
        "",
        f"- Run: {run_at:%Y-%m-%d %H:%M}, code version `{code_version}`",
        f"- Model: `{model}` via `{base_url}`",
        f"- **Passed: {passed} of {len(results)}** (failed: {failed}, errors: {errors})",
        f"- Model calls: {sum(r.model_calls for r in results)}, retries after rate limits or server errors: "
        f"{sum(r.retries for r in results)}, time: {minutes:.1f} min (without the pauses between questions)",
        "",
        "Generated by `python -m eval.run_eval` from `eval/questions.json`.",
        "",
        "| # | Question | Category | Result | Failed checks |",
        "| --- | --- | --- | --- | --- |",
    ]
    for i, r in enumerate(results, start=1):
        failed_checks = r.error or "; ".join(c.description for c in r.checks if not c.passed)
        lines.append(f"| {i} | {r.case['id']} | {r.case['category']} | {r.status} | {_cell(failed_checks)} |")

    lines += ["", "## Details"]
    for i, r in enumerate(results, start=1):
        lines += ["", f"### {i}. {r.case['id']}: {r.status}", ""]
        turns = r.case.get("turns") or [r.case["question"]]
        for n, turn in enumerate(turns):
            lines.append(f"**Customer:** {turn}")
            lines.append("")
            if n < len(r.answers):
                lines += ["**Agent:**", "", _quote(r.answers[n]), ""]
        lines += [f"**Expected:** {r.case['expected']}", ""]
        if r.tool_calls:
            lines.append("**Tool calls:**")
            lines.append("")
            for call in r.tool_calls:
                args = json.dumps(call.arguments, ensure_ascii=False)
                summary = _result_summary(call.result)
                lines.append(f"- `{call.name}({args})` → {summary}")
            lines.append("")
        else:
            lines += ["**Tool calls:** none", ""]
        if r.error:
            lines += [f"**Error:** {r.error}", ""]
        if r.checks:
            lines += ["**Checks:**", ""]
        for check in r.checks:
            mark = "✅" if check.passed else "❌"
            lines.append(
                f"- {mark} {check.description}" + (f" ({check.detail})" if check.detail and not check.passed else "")
            )
        calls = f"{r.model_calls} model call" + ("" if r.model_calls == 1 else "s")
        retries = f", {r.retries} " + ("retry" if r.retries == 1 else "retries") if r.retries else ""
        lines.append(f"\n_{r.seconds:.1f} s, {calls}{retries}_")
    return "\n".join(lines) + "\n"


def code_version() -> str:
    """The git commit the evaluation ran on, so results can be traced back to the code."""
    try:
        commit = _git("rev-parse", "--short", "HEAD")
        changed = _git("status", "--porcelain", "--untracked-files=no")
    except (OSError, subprocess.CalledProcessError):
        return "unknown"
    return f"{commit}, with uncommitted changes" if changed else commit


def _git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=PROJECT_ROOT, capture_output=True, text=True, check=True).stdout.strip()


def _result_summary(result: dict) -> str:
    if "error" in result:
        return f"error: {result['error']}"
    if result.get("found") is False:
        return "not found"
    if "total_refund_eur" in result:
        return f"total_refund_eur={result['total_refund_eur']}, can_cancel={result.get('can_cancel')}"
    if "results" in result:
        sections = [f"{s['source'].split('/')[-1]}: {s['section']}" for s in result["results"]]
        return "; ".join(sections) or "no matches"
    if "booking" in result:
        return f"status={result['booking'].get('status')}"
    return "ok"


# --- command line ----------------------------------------------------------------


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m eval.run_eval", description=__doc__.split("\n\n")[0])
    parser.add_argument("--model", help="model name, overrides LLM_MODEL")
    parser.add_argument("--only", help="comma-separated question ids to run")
    parser.add_argument("--delay", type=float, default=5.0, help="seconds to wait between questions (default 5)")
    parser.add_argument("--output", type=Path, default=RESULTS_FILE, help="where to write the Markdown report")
    args = parser.parse_args(argv)

    load_dotenv(PROJECT_ROOT / ".env")
    try:
        settings = LLMSettings.from_env(model_override=args.model)
    except ConfigError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 2

    cases = load_cases()
    if args.only:
        wanted = {name.strip() for name in args.only.split(",")}
        cases = [case for case in cases if case["id"] in wanted]

    run_at = datetime.now()
    version = code_version()
    results = run_all(cases, lambda: build_agent(model_name=args.model), delay=args.delay)
    report = render_report(results, settings.model, settings.base_url, run_at, version)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(report, encoding="utf-8")

    passed = sum(r.passed for r in results)
    print(f"\nPassed {passed} of {len(results)}. Report: {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
